using System;
using System.Collections.Generic;

namespace ExtraPotions.Delve.Engine
{
    /// <summary>What Delve does with one dungeon type (<c>Delve.Dungeons.yml</c> <c>modes:</c>).</summary>
    public enum DungeonMode { Off, Resources, Full }

    public static class DungeonModes
    {
        /// <summary>
        /// Resources by default where RestockRegen regrows something (sunken crypts, frost caves, infested mines, Morkhalla,
        /// the Hole, the Queen's citadel); every other type Off (user decision Q3: full resets are opt-in per type).
        /// </summary>
        public static readonly IReadOnlyDictionary<string, DungeonMode> Defaults = new Dictionary<string, DungeonMode>(StringComparer.Ordinal)
        {
            ["DG_SunkenCrypt"] = DungeonMode.Resources,
            ["DG_Cave"] = DungeonMode.Resources,
            ["DG_DvergrTown"] = DungeonMode.Resources,
            ["DG_MorkHalla"] = DungeonMode.Resources,
            ["DG_Hole"] = DungeonMode.Resources,
            ["DG_DvergrBoss"] = DungeonMode.Resources,
        };

        public static DungeonMode Default(string generator) =>
            generator != null && Defaults.TryGetValue(generator, out var mode) ? mode : DungeonMode.Off;

        /// <summary>
        /// Whether a kind may act inside a dungeon of this mode. Exactly one of full reset (Full) and resource regrow and
        /// boss return (Resources) runs per type; chests inside a fully reset dungeon are regenerated by the reset, so the
        /// chest refill stays out of Full. Kinds that are not dungeon modes (chests elsewhere, world objects, spawners)
        /// are always allowed here; their own switches decide.
        /// </summary>
        public static bool Allows(DungeonMode mode, DelveKind kind)
        {
            switch (kind)
            {
                case DelveKind.FullReset:
                    return mode == DungeonMode.Full;
                case DelveKind.MudPiles:
                case DelveKind.FrostCaveCrystals:
                case DelveKind.BlackCores:
                case DelveKind.Morkhalla:
                case DelveKind.Hole:
                case DelveKind.Queen:
                    return mode == DungeonMode.Resources;
                case DelveKind.Chests:
                    return mode != DungeonMode.Full;
                default:
                    return true;
            }
        }
    }
}
